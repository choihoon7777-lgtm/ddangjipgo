-- Restricted, server-only enqueue. The allowlist is enforced by table constraints.
create or replace function public.df_media_collect_feeds()
returns jsonb language plpgsql security definer set search_path=public,extensions,pg_temp
as $$
declare f record; request_id bigint; cnt int:=0; faults int:=0;
begin
 if not pg_try_advisory_xact_lock(932610,1) then return jsonb_build_object('ok',false,'reason','busy'); end if;
 for f in select * from public.df_media_feeds where enabled order by id loop
  begin
   select net.http_get(url:=f.feed_url,timeout_milliseconds:=15000) into request_id;
   insert into public.df_media_feed_requests(feed_id,request_id) values(f.id,request_id);
   update public.df_media_feeds set last_checked_at=now(),last_status='queued',last_error=null where id=f.id;
   cnt:=cnt+1;
  exception when others then
   faults:=faults+1;
   update public.df_media_feeds set last_checked_at=now(),last_status='failed',last_error=left(sqlerrm,200) where id=f.id;
  end;
 end loop;
 return jsonb_build_object('ok',faults=0,'requested',cnt,'failed',faults);
end
$$;
revoke all on function public.df_media_collect_feeds() from public,anon,authenticated;

-- Parse only XML title, link, date. Even when the RSS <description> contains a
-- whole copyrighted article, the description is NEVER extracted or stored.
create or replace function public.df_media_ingest_ready()
returns jsonb language plpgsql security definer set search_path=public,extensions,pg_temp
as $$
declare
 req record; item xml; raw_head text; raw_url text; raw_date text;
 head text; link text; date_at timestamptz; topic text; rating int;
 items_seen int; created int; sum_new int:=0; checked int:=0; faults int:=0;
begin
 if not pg_try_advisory_xact_lock(932610,2) then return jsonb_build_object('ok',false,'reason','busy'); end if;
 for req in
  select q.id, q.feed_id, q.request_id, q.requested_at,
         f.publisher,f.section,f.site_host,
         response.status_code,response.content,response.error_msg,response.timed_out
  from public.df_media_feed_requests q
  join public.df_media_feeds f on f.id=q.feed_id
  left join net._http_response response on response.id=q.request_id
  where q.processed_at is null and q.requested_at<now()-interval '12 seconds'
  order by q.requested_at, q.id limit 35
 loop
  -- Keep pending if a network request has not yet finished, until 3 minutes.
  if req.status_code is null and req.error_msg is null and coalesce(req.timed_out,false)=false
     and req.requested_at>now()-interval '3 minutes' then continue; end if;
  items_seen:=0;created:=0;
  begin
   if coalesce(req.status_code,0)<>200 then raise exception 'HTTP_% (%)',coalesce(req.status_code,0),left(coalesce(req.error_msg,'upstream error'),150); end if;
   if length(req.content)>1300000 or req.content not like '%<rss%' then raise exception 'NOT_VALID_RSS_OR_TOO_BIG'; end if;
   for item in select unnest(xpath('/rss/channel/item',xmlparse(document req.content))) loop
    items_seen:=items_seen+1;
    raw_head:=(xpath('/item/title/text()',item))[1]::text;
    raw_url:=(xpath('/item/link/text()',item))[1]::text;
    raw_date:=(xpath('/item/pubDate/text()',item))[1]::text;
    head:=btrim(replace(replace(coalesce(raw_head,''),'<![CDATA[',''),']]>',''));
    link:=btrim(replace(replace(coalesce(raw_url,''),'<![CDATA[',''),']]>',''));
    if char_length(head) not between 9 and 280 or char_length(link)>1024 then continue; end if;
    -- Explicit host match stops open redirects and arbitrary URLs.
    if link not like 'https://' || req.site_host || '/%' or link ~ '[[:space:]]' then continue; end if;
    if head !~ '(도시개발|개발사업|도시계획|도시정비|신도시|공공주택|주택공급|아파트|분양|미분양|임대주택|재건축|재개발|정비사업|재정비|주택시장|건설사|건설공사|공사비|건설경기|산업단지|산단|택지|토지보상|용적률|지구단위|부동산|철도|GTX|광역교통|지하철|SOC|주거정책|PF|인허가|공공개발|그린벨트|건축허가|도시철도|공장부지|공공시설)' then continue; end if;
    -- Exclude foreign-market pieces and unrelated equity-price commentary.
    if head ~ '(대만 증시|일본 증시|美 증시|中 증시|코스피|코스닥|주가 급등|증시 하락|선물지수|신차 출시|골프|연예인)' then continue; end if;
    begin date_at:=raw_date::timestamptz;exception when others then continue;end;
    if date_at>now()+interval '12 hours' or date_at<now()-interval '30 days' then continue; end if;
    topic:=case
      when head ~ '(재개발|재건축|정비사업|도시정비|재정비)' then '재개발·정비'
      when head ~ '(분양|청약|미분양|공급|아파트|임대주택)' then '주택·분양'
      when head ~ '(건설공사|건설사|공사비|PF|시공)' then '건설·금융'
      when head ~ '(철도|GTX|지하철|광역교통|도로|SOC)' then '교통·인프라'
      when head ~ '(산업단지|산단|공장부지|기업도시)' then '산업·개발'
      else '토지·도시개발' end;
    rating:=case when head ~ '(도시개발|개발사업|도시계획|지구단위|재개발|재건축|산업단지|공공주택|주택공급|토지보상|분양)' then 90
      when req.section='부동산' then 80 else 70 end;
    insert into public.df_media_leads(feed_id,publisher,headline,original_url,source_published_at,topic,score)
      values(req.feed_id,req.publisher,head,link,date_at,topic,rating)
      on conflict (original_url) do nothing;
    if found then created:=created+1;end if;
   end loop;
   update public.df_media_feed_requests set processed_at=now(),result='success',
      items_found=items_seen,leads_created=created,error_message=null where id=req.id;
   update public.df_media_feeds set last_processed_at=now(),last_status='success',
      last_new=created,last_error=null where id=req.feed_id;
   sum_new:=sum_new+created; checked:=checked+1;
  exception when others then
   faults:=faults+1;
   update public.df_media_feed_requests set processed_at=now(),result='failed',error_message=left(sqlerrm,190) where id=req.id;
   update public.df_media_feeds set last_processed_at=now(),last_status='failed',last_new=0,last_error=left(sqlerrm,190) where id=req.feed_id;
  end;
 end loop;
 return jsonb_build_object('ok',faults=0,'feeds_processed',checked,'new_candidates',sum_new,'failed',faults);
end
$$;
revoke all on function public.df_media_ingest_ready() from public,anon,authenticated;

