-- Development Focus media-monitoring factory.
-- RSS headline metadata only: NO article bodies, descriptions or copyrighted photos.
create table if not exists public.df_media_feeds (
 id bigint generated by default as identity primary key,
 publisher text not null,
 section text not null,
 feed_url text not null unique,
 site_host text not null,
 enabled boolean not null default true,
 last_checked_at timestamptz,
 last_processed_at timestamptz,
 last_status text,
 last_new integer not null default 0,
 last_error text,
 created_at timestamptz not null default now(),
 constraint df_media_allowed_feed check (
    (publisher='뉴시스' and feed_url ~ '^https://www[.]newsis[.]com/RSS/(economy|industry|met|country)[.]xml$' and site_host='www.newsis.com')
 or (publisher='매일경제' and feed_url ~ '^https://www[.]mk[.]co[.]kr/rss/(50300009|30100041)/$' and site_host='www.mk.co.kr')
 or (publisher='연합뉴스' and feed_url='https://www.yna.co.kr/rss/economy.xml' and site_host='www.yna.co.kr')
 )
);
create table if not exists public.df_media_feed_requests (
 id bigint generated always as identity primary key,
 feed_id bigint not null references public.df_media_feeds(id) on delete restrict,
 request_id bigint not null unique,
 requested_at timestamptz not null default now(),
 processed_at timestamptz,
 result text not null default 'queued' check(result in ('queued','success','failed')),
 items_found integer not null default 0,
 leads_created integer not null default 0,
 error_message text
);
create index if not exists df_media_pending_requests_idx on public.df_media_feed_requests(requested_at)
 where processed_at is null;
create table if not exists public.df_media_leads (
 id uuid primary key default gen_random_uuid(),
 feed_id bigint not null references public.df_media_feeds(id) on delete restrict,
 publisher text not null,
 headline text not null,
 original_url text not null unique,
 source_published_at timestamptz not null,
 topic text not null,
 score integer not null,
 review_status text not null default 'candidate' check(review_status in ('candidate','reviewing','verified','rejected')),
 verified_official_url text,
 editor_note text,
 first_seen_at timestamptz not null default now(),
 last_seen_at timestamptz not null default now(),
 reviewed_at timestamptz,
 constraint df_media_title_length check (char_length(headline) between 9 and 280),
 constraint df_media_verified_official_https check (verified_official_url is null or verified_official_url ~ '^https://')
);
create index if not exists df_media_leads_recent_idx on public.df_media_leads(first_seen_at desc);
create index if not exists df_media_leads_status_idx on public.df_media_leads(review_status,source_published_at desc);

alter table public.df_media_feeds enable row level security;
alter table public.df_media_feed_requests enable row level security;
alter table public.df_media_leads enable row level security;
revoke all on public.df_media_feeds,public.df_media_feed_requests,public.df_media_leads from public,anon,authenticated;
grant select on public.df_media_feeds,public.df_media_feed_requests,public.df_media_leads to authenticated;
grant update(review_status,verified_official_url,editor_note,reviewed_at) on public.df_media_leads to authenticated;
drop policy if exists df_media_feeds_admin_read on public.df_media_feeds;
create policy df_media_feeds_admin_read on public.df_media_feeds for select to authenticated using (public.df_is_admin());
drop policy if exists df_media_requests_admin_read on public.df_media_feed_requests;
create policy df_media_requests_admin_read on public.df_media_feed_requests for select to authenticated using (public.df_is_admin());
drop policy if exists df_media_leads_admin_read on public.df_media_leads;
create policy df_media_leads_admin_read on public.df_media_leads for select to authenticated using (public.df_is_admin());
drop policy if exists df_media_leads_admin_update on public.df_media_leads;
create policy df_media_leads_admin_update on public.df_media_leads for update to authenticated using (public.df_is_admin()) with check (public.df_is_admin());

